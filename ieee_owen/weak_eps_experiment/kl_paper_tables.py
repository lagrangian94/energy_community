"""
Emit the LaTeX bodies of tab:results and tab:runtime of the uncertainty manuscript
(manuscript_ieee_uncertainty.tex) from the KL runs, and the numbers its text quotes.

Same rule as paper_tables.py: the tables are generated, not typed. Sources:
  stochastic/main17_xi/*_main.json   main runs (run_kl_main.py), |Omega| = 20
  stochastic/bench17_xi/bench.csv    benchmarks (run_kl_bench.py)

CONVENTIONS.
- Geometric mean of |x| over the days, sign restored (val(DP_N) is a net cost here,
  so it prints negative). A cell with no data prints \\TBD{--}; one that rests on
  fewer days than the caption says prints inside \\TBD{} with the count in a comment.
- The extensive form stops at a gap of 1e-4 or 30 minutes, and g and eps rest on
  its incumbent. A day whose extensive form was re-solved later (resolve_ef.py) is
  read from 'ef_first', the 30-minute plan, so every day follows the same rule
  (kl_experiment_plan.md, sec. 8.11).
- eps(chi) measured: no Dinkelbach (sec. 8.12). A single member j gains
  val({j}) - chi_j by leaving, which bounds eps(chi) from below, and eps_K bounds it
  from above; where the two agree on every day the cell is exact. Printed only for
  the sizes at which a member gains on all days.

Usage:  python ieee_owen/weak_eps_experiment/kl_paper_tables.py [--out ieee_owen/kl_tables.tex]
"""
import os, glob, json, argparse
import numpy as np

_HERE = os.path.dirname(os.path.abspath(__file__))
MAIN = os.path.join(_HERE, 'stochastic', 'main17_xi')
BENCH = os.path.join(_HERE, 'stochastic', 'bench17_xi')
SIZES = (6, 15, 30, 60)
DAYS = 31


def gm(a):
    a = np.asarray(a, float)
    a = a[np.isfinite(a) & (a != 0)]
    if not len(a):
        return None
    s = -1.0 if (a < 0).all() else 1.0
    return s * float(np.exp(np.mean(np.log(np.abs(a)))))


def num(x, digits):
    if x is None:
        return r'\TBD{--}'
    s = f'{abs(x):,.{digits}f}'.replace(',', '{,}')
    return ('$-$' if x < 0 else '') + s


def main_rows(scen):
    out = {}
    for n in SIZES:
        r = {k: [] for k in ('val', 'vdr', 'g', 'eps', 't_ef', 't_rcg', 'single', 'capped')}
        for f in glob.glob(os.path.join(MAIN, f'{n}p_*_S{scen}_*_main.json')):
            j = json.load(open(f))
            ef = j['ef_first']['ef'] if 'ef_first' in j else j['ef']
            g = ef['obj'] - j['dw']['lb']
            owen, alone = j['allocation']['owen'], j['standalone']
            r['val'].append(-ef['obj'])
            r['vdr'].append(-ef['obj'] - sum(alone.values()))
            r['g'].append(g)
            r['eps'].append(g / n)
            r['t_ef'].append(ef['time_solve'])
            r['capped'].append(ef['status'] == 'timelimit')
            r['t_rcg'].append(j['dw']['time'])
            r['single'].append(max(alone[u] - (owen[u] - g / n) for u in owen))
        out[n] = r
    return out


def bench_rows(scen):
    path = os.path.join(BENCH, 'bench.csv')
    out = {}
    if not os.path.exists(path):
        return out
    lines = open(path).read().splitlines()
    head = lines[0].split(',')
    for ln in lines[1:]:
        f = dict(zip(head, ln.split(',')))
        if int(f['scen']) == scen:
            out.setdefault((f['method'], int(f['n'])), []).append(f)
    return out


def cell(vals, digits, days=DAYS):
    """Geometric mean; inside \\TBD{} while fewer than `days` days are in."""
    x = gm(vals)
    if x is None:
        return r'\TBD{--}'
    return num(x, digits) if len(vals) >= days else rf'\TBD{{{num(x, digits)}}}'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--scen', type=int, default=20)
    ap.add_argument('--out', default=os.path.join(os.path.dirname(_HERE), 'kl_tables.tex'))
    a = ap.parse_args()
    R, B = main_rows(a.scen), bench_rows(a.scen)
    L = []
    w = L.append
    w(f'% GENERATED by weak_eps_experiment/kl_paper_tables.py (|Omega| = {a.scen}) -- do not edit')
    w('% days per size: ' + ', '.join(f'n={n}: {len(R[n]["g"])}' for n in SIZES))
    w('')
    w('% ---- tab:results')
    row = lambda name, key, d: w(f'{name} & ' + ' & '.join(cell(R[n][key], d) for n in SIZES) + r' \\')
    row(r'$\vdr{N}$', 'val', 0)
    row(r'$v^{\mathrm{DR}}(N)$', 'vdr', 0)
    row(r'$g_K^{\mathrm{LR\text{-}DR}}$', 'g', 2)
    w(r'$\varepsilon_K^{\mathrm{LR\text{-}DR}}=g_K^{\mathrm{LR\text{-}DR}}/n$ & '
      + ' & '.join(cell(R[n]['eps'], 3) for n in SIZES) + r' \\')
    w(r'Bound of Proposition~\ref{prop:eps} & ' + ' & '.join([r'\TBD{--}'] * 4) + r' \\')
    w(r'\midrule')
    meas = []
    for n in SIZES:
        s = np.array(R[n]['single'])
        meas.append(num(gm(s), 3) if len(s) >= DAYS and (s > 0).all() else r'\TBD{--}')
    w(r'$\varepsilon(\chi^{\mathrm{LR\text{-}DR}})$ measured & ' + ' & '.join(meas) + r' \\')
    w('')
    w('% ---- tab:runtime')
    w(r'Solving $\vdr{N}$ & ' + ' & '.join(cell(R[n]['t_ef'], 0) for n in SIZES) + r' \\')
    w(r'RCG, nested master & ' + ' & '.join(cell(R[n]['t_rcg'], 0) for n in SIZES) + r' \\')
    cg, conv = [], []
    for n in SIZES:
        rows = B.get(('coalgen', n), [])
        ok = [float(f['alg_s']) for f in rows if f['status'] == 'converged']
        cg.append(cell(ok, 0) if ok else (r'\TBD{$>3{,}600$}' if rows else r'\TBD{--}'))
        conv.append(rf'\TBD{{{len(ok)}/{len(rows)}}}' if rows else r'\TBD{--}')
    w(r'\midrule')
    w(r'Coalition generation & ' + ' & '.join(cg) + r' \\')
    w(r'\quad converged & ' + ' & '.join(conv) + r' \\')
    w('')
    w('% ---- quoted in the text')
    g = {n: gm(R[n]['g']) for n in SIZES}
    e = {n: gm(R[n]['eps']) for n in SIZES}
    w(f'% duality gap, geometric mean: ' + ', '.join(f'n={n}: {g[n]:.2f}' for n in SIZES))
    w(f'% eps_K, geometric mean: ' + ', '.join(f'n={n}: {e[n]:.3f}' for n in SIZES))
    w(f'% RCG time, geometric mean [s]: '
      + ', '.join(f'n={n}: {gm(R[n]["t_rcg"]):.0f}' for n in SIZES))
    for n in SIZES:
        s, ee = np.array(R[n]['single']), np.array(R[n]['eps'])
        w(f'% n={n}: a single member gains on {int((s > 0).sum())}/{len(s)} days; within 0.1% '
          f'of eps_K on {int((s >= 0.999 * ee).sum())}, above eps_K on {int((s > ee * (1 + 1e-9)).sum())}; '
          f'extensive form at its 30-minute cap on '
          f'{sum(R[n]["capped"])} days')
    text = '\n'.join(L) + '\n'
    with open(a.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print(text)
    print(f'wrote {a.out}')


if __name__ == '__main__':
    main()
